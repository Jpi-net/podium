import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { feedback, git, gitRaw, pattern, projectDir, readInput, run, setting } from './lib.mjs';

const TEXT_EXTENSIONS = new Set(['.cs', '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.vue', '.svelte', '.html', '.css', '.scss', '.json', '.sql', '.md', '.yml', '.yaml', '.xml', '.py', '.go', '.rs', '.java', '.kt', '.rb', '.php', '.sh', '.ps1']);
const LINE_COMMENT = {
    '.cs': /^\s*(\/\/(?!\/)|\/\*)/,
    '.ts': /^\s*(\/\/|\/\*)/,
    '.tsx': /^\s*(\/\/|\/\*|\{\/\*)/,
    '.js': /^\s*(\/\/|\/\*)/,
    '.jsx': /^\s*(\/\/|\/\*|\{\/\*)/,
    '.mjs': /^\s*(\/\/|\/\*)/,
    '.css': /^\s*\/\*/,
    '.scss': /^\s*(\/\/|\/\*)/,
    '.less': /^\s*(\/\/|\/\*)/,
    '.java': /^\s*(\/\/|\/\*)/,
    '.kt': /^\s*(\/\/|\/\*)/,
    '.go': /^\s*(\/\/|\/\*)/,
    '.rs': /^\s*\/\/(?![/!])/,
    '.php': /^\s*(\/\/|#|\/\*)/,
    '.py': /^\s*#(?!!)/,
    '.rb': /^\s*#(?!!)/,
    '.sh': /^\s*#(?!!)/,
    '.html': /<!--/,
    '.vue': /<!--|^\s*\/\//,
    '.sql': /^\s*(--|\/\*)/,
};
const DIRECTIVES = /eslint-disable|@ts-expect-error|@ts-ignore|prettier-ignore|#pragma|<auto-generated|noqa|type:\s*ignore|nolint|@SuppressWarnings|^\s*\/\/\/|^\s*#\s*(region|endregion)/;
const SUSPICIOUS = [
    [/\b(it|describe|test)\.only\(|\bf(it|describe)\(|^\s*@only\b|@pytest\.mark\.only/, 'focused test left (.only / fit / fdescribe)'],
    [/\b(it|describe|test)\.skip\(|\bx(it|describe)\(|\[(Fact|Theory)\s*\(\s*Skip\s*=|@Disabled\b|@pytest\.mark\.skip\b/, 'skipped test added'],
    [/\bconsole\.(log|debug)\(|\bdebugger;|^\s*print\(.*\bdebug\b|\bdbg!\(|\bfmt\.Println\("DEBUG/, 'debug output left'],
];
const BOM = '﻿';

const input = readInput();
const root = projectDir();
const filePath = input.tool_input?.file_path;

if (!filePath || !existsSync(filePath)) {
    process.exit(0);
}

const relativePath = relative(root, filePath).split(sep).join('/');

if (relativePath.startsWith('..')) {
    process.exit(0);
}

if (relativePath.startsWith('.claude/')) {
    if (relativePath.endsWith('.json')) {
        try {
            JSON.parse(readFileSync(filePath, 'utf8'));
        } catch (error) {
            feedback(`Invalid JSON in ${relativePath}: ${error.message}`);
        }
    }

    if (relativePath.endsWith('.mjs')) {
        const check = run(`node --check "${filePath}"`, root, 15000);

        if (!check.ok) {
            feedback(`Syntax error in ${relativePath}:\n${check.output.split('\n').slice(0, 8).join('\n')}`);
        }
    }

    if (/\/(agents|skills)\/.*\.md$/.test(relativePath) && !/^---\r?\n[\s\S]*?\bname:\s*\S[\s\S]*?\bdescription:\s*\S[\s\S]*?\r?\n---/.test(readFileSync(filePath, 'utf8'))) {
        feedback(`${relativePath} needs a front matter with name and description.`);
    }

    process.exit(0);
}

const generated = pattern(setting('generated', ''));

if (generated && generated.test(relativePath)) {
    process.exit(0);
}

const extension = filePath.slice(filePath.lastIndexOf('.')).toLowerCase();
const written = input.tool_input?.new_string
    ?? input.tool_input?.content
    ?? (input.tool_input?.edits ?? []).map(edit => edit.new_string).join('\n');
const previousLines = new Set([
    ...(input.tool_input?.old_string ?? '').split(/\r?\n/),
    ...(input.tool_input?.edits ?? []).flatMap(edit => (edit.old_string ?? '').split(/\r?\n/)),
    ...git(root, 'show', `HEAD:${relativePath}`).split(/\r?\n/),
].filter(line => line.trim() !== ''));
const added = written.split(/\r?\n/).filter(line => line.trim() !== '' && !previousLines.has(line));
const problems = [];

if (setting('checks.comments', false) && LINE_COMMENT[extension]) {
    const allow = pattern(setting('hooks.commentAllow', ''));
    const comments = added.filter(line => LINE_COMMENT[extension].test(line) && !DIRECTIVES.test(line) && !(allow && allow.test(line)));

    if (comments.length > 0) {
        problems.push(`Zero-comment rule violated in ${relativePath}. Remove:\n${comments.slice(0, 5).map(line => `  ${line.trim()}`).join('\n')}`);
    }
}

if (setting('checks.noVar', false) && ['.cs', '.js', '.jsx', '.ts', '.tsx', '.mjs'].includes(extension)) {
    const varLines = added.filter(line => /(^|[\s(;])var\s+[A-Za-z_$(]/.test(line) && !LINE_COMMENT[extension]?.test(line));

    if (varLines.length > 0) {
        problems.push(`No "var" in ${relativePath}: ${extension === '.cs' ? 'use explicit types' : 'use const or let'}.\n${varLines.slice(0, 3).map(line => `  ${line.trim()}`).join('\n')}`);
    }
}

for (const [regex, label] of SUSPICIOUS) {
    const hits = added.filter(line => regex.test(line));

    if (hits.length > 0) {
        problems.push(`${label} in ${relativePath}. Remove it unless the user asked for it:\n${hits.slice(0, 3).map(line => `  ${line.trim()}`).join('\n')}`);
    }
}

function detectStyle(content) {
    return { crlf: /\r\n/.test(content), bom: content.startsWith(BOM) };
}

function referenceStyle() {
    const original = gitRaw(root, 'show', `HEAD:${relativePath}`);

    if (original !== '') {
        return detectStyle(original);
    }

    const sibling = readdirSync(dirname(filePath)).find(name => name.toLowerCase().endsWith(extension) && join(dirname(filePath), name) !== filePath);

    return sibling ? detectStyle(readFileSync(join(dirname(filePath), sibling), 'utf8')) : null;
}

if (TEXT_EXTENSIONS.has(extension)) {
    const style = referenceStyle();

    if (style) {
        const content = readFileSync(filePath, 'utf8');
        const body = content.replace(/^﻿/, '').replace(/\r\n/g, '\n');
        const normalized = (style.bom ? BOM : '') + (style.crlf ? body.replace(/\n/g, '\r\n') : body);

        if (normalized !== content) {
            writeFileSync(filePath, normalized, 'utf8');
        }
    }
}

if (problems.length > 0) {
    feedback(problems.join('\n\n'));
}

process.exit(0);
